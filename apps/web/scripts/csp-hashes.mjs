#!/usr/bin/env node
/**
 * L7: strict CSP for the Next static export without 'unsafe-inline' for scripts.
 *
 * Runs as `postbuild`: scans out/** /*.html, hashes every inline <script> (sha256, exact bytes
 * as served) and writes
 *   - .csp/csp-hashes.json   — machine-readable list (tests, other proxies)
 *   - .csp/nginx-csp.conf    — `add_header Content-Security-Policy "..." always;`
 * The web image / native nginx include .csp/*.conf in `location /`.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const INLINE_SCRIPT_RE = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;

/** Inline (no src) executable scripts of an HTML document. JSON data blocks are skipped. */
export function inlineScripts(html) {
  const out = [];
  for (const m of html.matchAll(INLINE_SCRIPT_RE)) {
    const attrs = m[1] ?? '';
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
    if (type && !['text/javascript', 'module', 'application/javascript'].includes(type)) continue;
    out.push(m[2]);
  }
  return out;
}

export function sha256Source(content) {
  return `'sha256-${createHash('sha256').update(content, 'utf8').digest('base64')}'`;
}

export function collectHashes(outDir) {
  const hashes = new Set();
  const pages = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name.endsWith('.html')) pages.push(p);
    }
  };
  walk(outDir);
  for (const page of pages.sort()) {
    for (const s of inlineScripts(readFileSync(page, 'utf8'))) hashes.add(sha256Source(s));
  }
  return { pages: pages.map((p) => relative(outDir, p)), hashes: [...hashes].sort() };
}

export function buildPolicy(hashes) {
  return [
    "default-src 'self'",
    "img-src 'self' data: blob: https:",
    "style-src 'self' 'unsafe-inline'",
    `script-src 'self' ${hashes.join(' ')}`.trim(),
    "connect-src 'self'",
    "font-src 'self' data:",
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "frame-ancestors 'self'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
}

export function nginxSnippet(policy) {
  if (policy.includes('"')) throw new Error('CSP must not contain double quotes');
  return `# Generated by apps/web/scripts/csp-hashes.mjs (postbuild). Do not edit.\nadd_header Content-Security-Policy "${policy}" always;\n`;
}

function main() {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const outDir = join(root, 'out');
  const cspDir = join(root, '.csp');
  const { pages, hashes } = collectHashes(outDir);
  if (!pages.length) throw new Error(`no HTML in ${outDir} — run next build first`);
  const policy = buildPolicy(hashes);
  mkdirSync(cspDir, { recursive: true });
  writeFileSync(join(cspDir, 'csp-hashes.json'), JSON.stringify({ pages: pages.length, hashes, policy }, null, 2) + '\n');
  writeFileSync(join(cspDir, 'nginx-csp.conf'), nginxSnippet(policy));
  console.log(`CSP: ${hashes.length} inline script hashes from ${pages.length} pages → .csp/nginx-csp.conf (${policy.length} bytes)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
