const BY_LOCALE: Record<Locale, Record<string, RoleInstructions>> = {
  uk: INSTRUCTIONS_UK,
  ru: INSTRUCTIONS_RU,
};

/** @deprecated Use getInstructionsForRole(role, locale) */
export const INSTRUCTIONS = INSTRUCTIONS_UK;

export function getInstructionsForRole(
  role: string,
  locale: Locale = 'uk',
): RoleInstructions {
  const dict = BY_LOCALE[locale] ?? BY_LOCALE.uk;
  return dict[role] ?? FALLBACK[locale] ?? FALLBACK.uk;
}

export const INSTRUCTIONS_NAV_LABEL = 'Інструкція користування';

export function getInstructionsHref(role: string): string {
  if (role === 'resident') return '/resident/instructions';
  return '/admin/instructions';
}
