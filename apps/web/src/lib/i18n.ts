export type I18nKey = keyof (typeof DICT)['uk'];

function interpolate(template: string, params?: TParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = params[k];
    return v == null ? '' : String(v);
  });
}

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'uk';
  const raw = localStorage.getItem(STORAGE_KEY);
  return raw === 'ru' ? 'ru' : 'uk';
}

export function setStoredLocale(locale: Locale) {
  if (typeof window === 'undefined') return;
  localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
}

export function t(key: I18nKey, locale?: Locale, params?: TParams): string {
  const loc = locale ?? (typeof window !== 'undefined' ? getStoredLocale() : 'uk');
  const raw = DICT[loc][key] ?? DICT.uk[key] ?? key;
  return interpolate(String(raw), params);
}

